#!/usr/bin/env python3
"""Regenerate the shared top navigation in index.html, corpus.html and benchmarks.html.

Idempotent: the nav lives between <!-- SITE-NAV:BEGIN --> and <!-- SITE-NAV:END -->.
Behaviour/styles: assets/site-nav.css + assets/site-nav.js. Edit labels HERE, then run:
    python scripts/build_site_nav.py
"""
import re, pathlib, html

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN, END = '<!-- SITE-NAV:BEGIN (generated by scripts/build_site_nav.py) -->', '<!-- SITE-NAV:END -->'

# (href, page-file for aria-current, TR, EN)
PRIMARY = [
    ('corpus.html', 'corpus.html', 'Araştırma', 'Research'),
    ('benchmarks.html', 'benchmarks.html', 'Kıyaslamalar', 'Benchmarks'),
    ('index.html#labs', None, 'Laboratuvar', 'Labs'),
    ('index.html#learning', None, 'Öğren', 'Learn'),
]
# (href, TR title, EN title, TR hint, EN hint, external)
MORE = [
    ('index.html#milestones', 'Rekorlar & İspatlar', 'Records & Proofs', '9 dünya rekoru, Lean 4 sertifikaları', '9 world records, Lean 4 certificates', False),
    ('index.html#ecosystem', 'Ekosistem', 'Ecosystem', 'Listelemeler ve açık kaynak kabulleri', 'Listings and open-source inclusions', False),
    ('index.html#grants', 'Hibeler & Destekler', 'Grants & Support', 'Başvurular ve kurumsal destek', 'Applications and institutional support', False),
    ('index.html#team', 'Ekip & Atıf', 'Team & Citation', 'Yazarlar, BibTeX, lisans', 'Authors, BibTeX, licensing', False),
    ('demos/snake.html', '1v1 Yılan Arenası', '1v1 Snake Arena', 'Canlı meydan okuma demosu', 'Live challenge demo', False),
    None,
    ('https://werr.io', 'Werr.io', 'Werr.io', 'Açık motor ve kıyaslamalar', 'Open engine and benchmarks', True),
    ('https://github.com/pCwOrM/fractal-neural-synthesis', 'GitHub', 'GitHub', 'Kaynak kod ve veri', 'Source code and data', True),
    ('https://huggingface.co/pCwOrM', 'Hugging Face', 'Hugging Face', 'Modeller ve veri kümeleri', 'Models and datasets', True),
]
PAGES = {
    'index.html':      dict(lang='tr', tag=None, theme=False),
    'corpus.html':     dict(lang='en', tag=None, theme=False),
    'benchmarks.html': dict(lang='en', tag=('The Gauntlet', 'The Gauntlet'), theme=True),
}
ICON_B = '<svg class="b" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M4 7h16M4 12h16M4 17h16"/></svg>'
ICON_X = '<svg class="x" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M6 6l12 12M18 6L6 18"/></svg>'
CARET = '<svg class="site-nav__caret" viewBox="0 0 10 10" fill="none" stroke="currentColor" stroke-width="1.6" aria-hidden="true"><path d="M2 3.5l3 3 3-3"/></svg>'


def span(tr, en, cur, cls=''):
    t = tr if cur == 'tr' else en
    c = f' class="{cls}"' if cls else ''
    return f'<span{c} data-tr="{html.escape(tr)}" data-en="{html.escape(en)}">{html.escape(t)}</span>'


def build(page, cfg):
    cur = cfg['lang']
    L = []
    a = L.append
    a(BEGIN)
    a('<nav class="site-nav" aria-label="' + ('Ana gezinti' if cur == 'tr' else 'Main') + '" data-open="false">')
    a('  <div class="site-nav__bar">')
    a('    <a class="site-nav__brand" href="index.html" aria-label="Fractal Neural Synthesis">')
    a('      <img src="assets/fns_logo_nav.svg" alt="" width="28" height="28">')
    a('      <span class="site-nav__full">Fractal Neural Synthesis</span><span class="site-nav__short">FNS</span>')
    if cfg['tag']:
        a(f'      <span class="site-nav__tag">{html.escape(cfg["tag"][0])}</span>')
    a('    </a>')
    a('    <div class="site-nav__menu" id="siteNavMenu">')
    for href, pg, tr, en in PRIMARY:
        cp = f' data-page="{pg}"' if pg else ''
        a(f'      <a class="site-nav__link" href="{href}"{cp}>{span(tr, en, cur)}</a>')
    a('      <div class="site-nav__dd">')
    a('        <button type="button" class="site-nav__dd-btn" aria-expanded="false" aria-haspopup="true" aria-controls="siteNavMore">'
      + span('Daha fazla', 'More', cur) + CARET + '</button>')
    a(f'        <div class="site-nav__panel" id="siteNavMore" hidden data-title="{"Daha fazla" if cur == "tr" else "More"}" data-title-tr="Daha fazla" data-title-en="More">')
    for it in MORE:
        if it is None:
            a('          <div class="site-nav__sep" role="separator"></div>')
            continue
        href, ttr, ten, htr, hen, ext = it
        e = ' target="_blank" rel="noopener noreferrer"' if ext else ''
        arrow = ' ↗' if ext else ''
        a(f'          <a class="site-nav__item" href="{href}"{e}><b>{span(ttr, ten, cur)}{arrow}</b><small>{span(htr, hen, cur)}</small></a>')
    a('        </div>')
    a('      </div>')
    a('    </div>')
    a('    <div class="site-nav__actions">')
    if cfg['theme']:
        a('      <button type="button" class="site-nav__btn" id="btnTheme" title="Toggle light/dark theme" aria-label="Toggle light/dark theme"><span id="themeIcon" aria-hidden="true">☀️</span><span class="site-nav__btn-text" id="themeLabel">Light</span></button>')
    if page == 'benchmarks.html':
        a('      <button type="button" class="site-nav__btn" id="btnLang" title="Switch language / Dili değiştir" aria-label="Switch language / Dili değiştir"><span aria-hidden="true">🌐</span><span class="site-nav__btn-text" id="langLabel">Türkçe</span></button>')
    else:
        lab = 'English' if cur == 'tr' else 'Türkçe'
        a(f'      <button type="button" class="site-nav__btn" id="langBtn" onclick="toggleLanguage()" title="Switch language / Dili değiştir" aria-label="Switch language / Dili değiştir"><span aria-hidden="true">🌐</span><span class="site-nav__btn-text" id="langLabel">{lab}</span></button>')
    a('      <button type="button" class="site-nav__toggle" aria-expanded="false" aria-controls="siteNavMenu" '
      'data-label-open-tr="Menüyü aç" data-label-close-tr="Menüyü kapat" data-label-open-en="Open menu" data-label-close-en="Close menu" aria-label="'
      + ('Menüyü aç' if cur == 'tr' else 'Open menu') + '">' + ICON_B + ICON_X + '</button>')
    a('    </div>')
    a('  </div>')
    a('</nav>')
    a(END)
    return '\n'.join(L)


def apply(page, cfg):
    p = ROOT / page
    s = p.read_text(encoding='utf-8')
    block = build(page, cfg)
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: block, s, flags=re.S)
    else:
        s, n = re.subn(r'[ \t]*<nav class="top-nav">.*?</nav>', lambda m: block, s, count=1, flags=re.S)
        assert n == 1, page
    if 'assets/site-nav.css' not in s:
        s = s.replace('</head>', '  <link rel="stylesheet" href="assets/site-nav.css">\n</head>', 1)
    if 'assets/site-nav.js' not in s:
        s = s.replace('</body>', '  <script src="assets/site-nav.js" defer></script>\n</body>', 1)
    p.write_text(s, encoding='utf-8')


if __name__ == '__main__':
    for pg, cfg in PAGES.items():
        apply(pg, cfg)
        print('nav updated:', pg)
